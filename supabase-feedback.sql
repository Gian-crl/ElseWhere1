-- PURPOSE: creates a table for visitor names, 1–5 star ratings, comments, and timestamps.
-- Run this in the Supabase SQL Editor to enable public shared reviews.
create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  name text not null default 'A traveler' check (char_length(name) <= 60),
  rating integer not null check (rating between 1 and 5),
  comment text not null check (char_length(comment) between 1 and 1000),
  created_at timestamptz not null default now()
);
-- Row-level security restricts database access to the policies defined below.
alter table public.feedback enable row level security;
drop policy if exists "Anyone can read feedback" on public.feedback;
-- Visitors can read posted feedback and submit validated reviews using the public anon role.
create policy "Anyone can read feedback" on public.feedback for select to anon using (true);
drop policy if exists "Anyone can post feedback" on public.feedback;
create policy "Anyone can post feedback" on public.feedback for insert to anon with check (rating between 1 and 5 and char_length(comment) between 1 and 1000 and char_length(name) <= 60);
